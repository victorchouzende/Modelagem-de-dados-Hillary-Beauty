-- 3.6 Log de auditoria: registra INSERT/UPDATE/DELETE das tabelas principais.
-- usuario = id do usuário autenticado quando a chamada vem da API do Supabase (JWT);
-- no SQL Editor é o papel do banco (ex.: postgres). SECURITY DEFINER para gravar mesmo com RLS ativo.
create or replace function fn_log_auditoria() returns trigger
language plpgsql security definer set search_path = public as $$
declare
    v_usuario text;
    v_claims  text := nullif(current_setting('request.jwt.claims', true), '');
    v_reg     jsonb;
begin
    begin
        v_usuario := (v_claims::jsonb) ->> 'sub';
    exception when others then
        v_usuario := null;
    end;
    v_usuario := coalesce(v_usuario, session_user::text);

    if tg_op = 'UPDATE' and to_jsonb(old) = to_jsonb(new) then
        return null;                                   -- nada mudou
    end if;
    -- o saldo do produto muda a cada movimentação; a própria movimentação já é o histórico
    if tg_op = 'UPDATE' and tg_table_name = 'produto'
       and (to_jsonb(old) - 'quantidade_atual') = (to_jsonb(new) - 'quantidade_atual') then
        return null;
    end if;

    v_reg := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;

    insert into log_auditoria (usuario, tabela, operacao, id_registro, dados_antes, dados_depois)
    values (v_usuario, tg_table_name, tg_op, v_reg ->> tg_argv[0],
            case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) end,
            case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) end);
    return null;
end $$;

revoke all on function fn_log_auditoria() from public;

create trigger tg_log_cliente after insert or update or delete on cliente
