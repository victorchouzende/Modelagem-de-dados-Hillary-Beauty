create table categoria_profissional (
    id_categoria         integer generated by default as identity primary key,
    nome                 varchar      not null,
    percentual_comissao  numeric(5,2) not null,
    constraint ck_categoria_percentual check (percentual_comissao between 0 and 100)
);

create table cliente (
    id_cliente       integer generated by default as identity primary key,
    nome             varchar not null,
    telefone         varchar not null,
    data_nascimento  date,
    data_cadastro    date    not null default current_date,
    status_cliente   varchar not null default 'Ativo',
    constraint ck_cliente_status check (status_cliente in ('Ativo', 'Inativo')),
    -- "anterior à data atual" é validado por trigger (seção 3.5): CHECK com current_date não é imutável
    constraint ck_cliente_nascimento_min check (data_nascimento is null or data_nascimento >= date '1900-01-01')
);

create table profissional (
    id_profissional      integer generated by default as identity primary key,
    nome                 varchar not null,
    telefone             varchar,
    status_profissional  varchar not null default 'Ativa',
    especialidade        varchar,                          -- opcional (a recepcionista não atua em procedimentos)
    id_categoria         integer references categoria_profissional (id_categoria),
    constraint ck_profissional_status check (status_profissional in ('Ativa', 'Inativa'))
);

create table procedimento (
    id_procedimento      integer generated by default as identity primary key,
    nome                 varchar       not null,
    descricao            text,
    duracao              integer       not null,           -- em minutos
    valor                numeric(10,2) not null,           -- valor de referência ("a partir de")
    intervalo_retorno    varchar,
    status_procedimento  varchar       not null default 'Ativo',
    constraint ck_procedimento_duracao check (duracao > 0),
    constraint ck_procedimento_valor   check (valor >= 0),
    constraint ck_procedimento_status  check (status_procedimento in ('Ativo', 'Inativo'))
);

-- Relacionamento N:N "habilitada a"
create table profissional_procedimento (
    id_profissional  integer not null references profissional (id_profissional),
    id_procedimento  integer not null references procedimento (id_procedimento),
    primary key (id_profissional, id_procedimento)
);

create table agendamento (
    id_agendamento      integer generated by default as identity primary key,
    id_cliente          integer not null references cliente (id_cliente),
    id_profissional     integer not null references profissional (id_profissional),
    id_procedimento     integer not null references procedimento (id_procedimento),
    data_agendamento    date    not null,
    horario_inicio      time    not null,
    horario_fim         time    not null,                  -- calculado por trigger: início + duração
    status_agendamento  varchar not null default 'Agendado',
    observacao          text,
    constraint ck_agendamento_status  check (status_agendamento in
        ('Agendado', 'Confirmado', 'Realizado', 'Cancelado', 'Não Compareceu')),
    constraint ck_agendamento_horario check (horario_fim > horario_inicio),
    -- permite que o atendimento garanta que cliente/profissional/procedimento
    -- são os mesmos do agendamento de origem
    constraint uq_agendamento_origem unique (id_agendamento, id_cliente, id_profissional, id_procedimento),
    -- O horário só é RESERVADO após o sinal (status Confirmado). Por isso as restrições abaixo
    -- valem apenas para Confirmado/Realizado; "Agendado" (aguardando o sinal) não reserva horário.
    -- RF08: a mesma profissional não pode ter dois horários reservados sobrepostos
    constraint ex_agendamento_conflito exclude using gist (
        id_profissional with =,
        tsrange(data_agendamento + horario_inicio, data_agendamento + horario_fim) with &&
    ) where (status_agendamento in ('Confirmado', 'Realizado')),
    -- a mesma cliente também não pode estar em dois horários reservados ao mesmo tempo
    constraint ex_agendamento_conflito_cliente exclude using gist (
        id_cliente with =,
        tsrange(data_agendamento + horario_inicio, data_agendamento + horario_fim) with &&
    ) where (status_agendamento in ('Confirmado', 'Realizado'))
);

create table atendimento (
    id_atendimento       integer generated by default as identity primary key,
    id_agendamento       integer not null unique,          -- garante a cardinalidade 0..1
    id_cliente           integer not null references cliente (id_cliente),
    id_profissional      integer not null references profissional (id_profissional),
    id_procedimento      integer not null references procedimento (id_procedimento),
    data_atendimento     date    not null,
    horario_atendimento  time    not null,
    observacao           text,
    constraint fk_atendimento_agendamento foreign key
        (id_agendamento, id_cliente, id_profissional, id_procedimento)
        references agendamento (id_agendamento, id_cliente, id_profissional, id_procedimento)
);

create table pagamento (
    id_pagamento    integer generated by default as identity primary key,
    id_agendamento  integer       not null references agendamento (id_agendamento),
    valor           numeric(10,2) not null,
    data_pagamento  date          not null default current_date,
    tipo_pagamento  varchar       not null,
    constraint ck_pagamento_valor check (valor > 0),
    constraint ck_pagamento_tipo  check (tipo_pagamento in ('Sinal', 'Restante'))
);

-- no máximo um sinal por agendamento
create unique index uq_pagamento_sinal on pagamento (id_agendamento) where tipo_pagamento = 'Sinal';

create table produto (
    id_produto        integer generated by default as identity primary key,
    nome              varchar not null,
    descricao         text,
    unidade_medida    varchar not null,
    quantidade_atual  numeric not null default 0,
    estoque_minimo    numeric not null default 0,
    status_produto    varchar not null default 'Ativo',
    constraint ck_produto_unidade check (unidade_medida in ('unidade', 'ml', 'g')),
    constraint ck_produto_qtd     check (quantidade_atual >= 0),
    constraint ck_produto_minimo  check (estoque_minimo >= 0),
    constraint ck_produto_status  check (status_produto in ('Ativo', 'Inativo'))
);

create table movimentacao_estoque (
    id_movimentacao    integer generated by default as identity primary key,
    id_produto         integer not null references produto (id_produto),
    tipo_movimentacao  varchar not null,
    quantidade         numeric not null,
    data_movimentacao  date    not null default current_date,
    motivo             varchar,
    id_atendimento     integer references atendimento (id_atendimento),
    constraint ck_mov_tipo       check (tipo_movimentacao in ('Entrada', 'Saída')),
    constraint ck_mov_quantidade check (quantidade > 0),
    -- motivo obrigatório nas entradas e nas saídas não ligadas a atendimento
    constraint ck_mov_motivo     check (motivo is not null
                                        or (tipo_movimentacao = 'Saída' and id_atendimento is not null))
);

-- Log de auditoria (seção "Log" do README): quem fez o quê e quando
