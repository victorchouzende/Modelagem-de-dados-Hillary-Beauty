-- 3.1 Agendamento: calcula horario_fim e valida as regras de agendamento
create or replace function fn_agendamento_validar() returns trigger
language plpgsql set search_path = public as $$
declare
    v_duracao integer;
begin
    -- todo agendamento nasce 'Agendado' (aguardando o sinal); o sinal só existe depois de criado
    if tg_op = 'INSERT' and new.status_agendamento <> 'Agendado' then
        raise exception 'Todo agendamento deve ser criado com status Agendado (recebido: %)',
                        new.status_agendamento;
    end if;

    -- horário de término = início + duração do procedimento
    if tg_op = 'INSERT'
       or new.id_procedimento is distinct from old.id_procedimento
       or new.horario_inicio  is distinct from old.horario_inicio then
        select duracao into v_duracao from procedimento where id_procedimento = new.id_procedimento;
        new.horario_fim := new.horario_inicio + make_interval(mins => v_duracao);
    end if;

    -- cliente ativo, profissional ativa e habilitada, procedimento ativo
    if tg_op = 'INSERT'
       or new.id_cliente      is distinct from old.id_cliente
       or new.id_profissional is distinct from old.id_profissional
       or new.id_procedimento is distinct from old.id_procedimento then

        if not exists (select 1 from cliente
                       where id_cliente = new.id_cliente and status_cliente = 'Ativo') then
            raise exception 'Cliente inexistente ou inativo';
        end if;
        if not exists (select 1 from profissional
                       where id_profissional = new.id_profissional and status_profissional = 'Ativa') then
            raise exception 'Profissional inexistente ou inativa';
        end if;
        if not exists (select 1 from procedimento
                       where id_procedimento = new.id_procedimento and status_procedimento = 'Ativo') then
            raise exception 'Procedimento inexistente ou inativo';
        end if;
        if not exists (select 1 from profissional_procedimento
                       where id_profissional = new.id_profissional
                         and id_procedimento = new.id_procedimento) then
            raise exception 'Profissional não habilitada para este procedimento';
        end if;
    end if;

    if tg_op = 'UPDATE' then
        -- Cancelado e Não Compareceu são estados finais: para remarcar, cria-se novo agendamento
        if old.status_agendamento in ('Cancelado', 'Não Compareceu')
           and new.status_agendamento <> old.status_agendamento then
            raise exception 'Agendamento % não pode ser reativado; crie um novo agendamento',
                            old.status_agendamento;
        end if;

        -- após a confirmação não é possível trocar ou remanejar o horário
        if old.status_agendamento in ('Confirmado', 'Realizado')
           and (new.data_agendamento is distinct from old.data_agendamento
             or new.horario_inicio   is distinct from old.horario_inicio
             or new.id_profissional  is distinct from old.id_profissional
             or new.id_procedimento  is distinct from old.id_procedimento) then
            raise exception 'Após a confirmação não é permitido trocar ou remanejar o horário';
        end if;

        -- só confirma com o sinal pago
        if old.status_agendamento = 'Agendado'
           and new.status_agendamento in ('Confirmado', 'Realizado') then
            if not exists (select 1 from pagamento
                           where id_agendamento = new.id_agendamento and tipo_pagamento = 'Sinal') then
                raise exception 'O agendamento só pode ser confirmado após o pagamento do sinal';
            end if;
        end if;
    end if;

    -- conflito de horário (RF08): o horário só fica reservado após o sinal, então o novo
    -- agendamento é comparado com os agendamentos de horário reservado (Confirmado/Realizado).
    -- Dois agendamentos ainda aguardando o sinal podem coexistir; o segundo a ser confirmado é recusado.
    -- (As restrições EXCLUDE da tabela continuam como garantia final.)
    if new.status_agendamento in ('Agendado', 'Confirmado', 'Realizado') then
        if exists (select 1 from agendamento a
                    where a.id_agendamento is distinct from new.id_agendamento
                      and a.id_profissional = new.id_profissional
                      and a.status_agendamento in ('Confirmado', 'Realizado')
                      and a.data_agendamento = new.data_agendamento
                      and a.horario_inicio < new.horario_fim
                      and a.horario_fim    > new.horario_inicio) then
            raise exception 'A profissional já possui um horário reservado neste período';
        end if;
        if exists (select 1 from agendamento a
                    where a.id_agendamento is distinct from new.id_agendamento
                      and a.id_cliente = new.id_cliente
                      and a.status_agendamento in ('Confirmado', 'Realizado')
                      and a.data_agendamento = new.data_agendamento
                      and a.horario_inicio < new.horario_fim
                      and a.horario_fim    > new.horario_inicio) then
            raise exception 'A cliente já possui um horário reservado neste período';
        end if;
    end if;

    return new;
end $$;

create trigger tg_agendamento_validar
    before insert or update on agendamento
    for each row execute function fn_agendamento_validar();


-- 3.2 Atendimento: só para agendamento confirmado ou realizado
create or replace function fn_atendimento_validar() returns trigger
language plpgsql set search_path = public as $$
declare
    v_status varchar;
begin
    select status_agendamento into v_status
      from agendamento where id_agendamento = new.id_agendamento;

    if v_status is null or v_status not in ('Confirmado', 'Realizado') then
        raise exception 'Atendimento só pode ser registrado para agendamento confirmado ou realizado (status atual: %)',
                        coalesce(v_status, 'inexistente');
    end if;
    return new;
end $$;

create trigger tg_atendimento_validar
    before insert on atendimento
    for each row execute function fn_atendimento_validar();


-- 3.3 Estoque: atualiza quantidade_atual e impede estoque negativo
create or replace function fn_movimentacao_aplicar() returns trigger
language plpgsql set search_path = public as $$
declare
    v_qtd    numeric;
    v_status varchar;
begin
    select quantidade_atual, status_produto into v_qtd, v_status
      from produto where id_produto = new.id_produto for update;

    if new.tipo_movimentacao = 'Saída' then
        if v_status <> 'Ativo' then
            raise exception 'Produto inativo não pode receber saídas';
        end if;
        if v_qtd < new.quantidade then
            raise exception 'Estoque insuficiente: disponível %, solicitado %', v_qtd, new.quantidade;
        end if;
        update produto set quantidade_atual = quantidade_atual - new.quantidade
         where id_produto = new.id_produto;
    else
        update produto set quantidade_atual = quantidade_atual + new.quantidade
         where id_produto = new.id_produto;
    end if;
    return new;
end $$;

create trigger tg_movimentacao_aplicar
    before insert on movimentacao_estoque
    for each row execute function fn_movimentacao_aplicar();


-- 3.4 Movimentação de estoque é um registro histórico imutável.
-- O saldo só é ajustado em INSERT; para corrigir um lançamento errado, registre uma movimentação contrária.
create or replace function fn_imutavel() returns trigger
language plpgsql set search_path = public as $$
begin
    if tg_table_name = 'log_auditoria' then
        raise exception 'O log de auditoria não pode ser alterado nem excluído';
    end if;
    raise exception 'Movimentações de estoque não podem ser alteradas nem excluídas; registre uma movimentação de ajuste/estorno';
end $$;

create trigger tg_movimentacao_imutavel
    before update or delete on movimentacao_estoque
    for each row execute function fn_imutavel();

-- o próprio log também não pode ser alterado nem apagado
create trigger tg_log_imutavel
    before update or delete on log_auditoria
    for each row execute function fn_imutavel();


