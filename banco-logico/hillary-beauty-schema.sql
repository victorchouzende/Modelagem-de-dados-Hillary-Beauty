-- RF12: produtos no estoque mínimo ou abaixo
create view vw_estoque_baixo with (security_invoker = true) as
select id_produto, nome, unidade_medida, quantidade_atual, estoque_minimo
  from produto
 where status_produto = 'Ativo' and quantidade_atual <= estoque_minimo;

-- RF13: atendimentos por profissional e mês
create view vw_atendimentos_por_profissional with (security_invoker = true) as
select p.id_profissional, p.nome as profissional,
       date_trunc('month', a.data_atendimento)::date as mes,
       count(*) as atendimentos
  from atendimento a
  join profissional p on p.id_profissional = a.id_profissional
 group by p.id_profissional, p.nome, date_trunc('month', a.data_atendimento);

-- RF13: atendimentos por procedimento e mês
create view vw_atendimentos_por_procedimento with (security_invoker = true) as
select pr.id_procedimento, pr.nome as procedimento,
       date_trunc('month', a.data_atendimento)::date as mes,
       count(*) as atendimentos
  from atendimento a
  join procedimento pr on pr.id_procedimento = a.id_procedimento
 group by pr.id_procedimento, pr.nome, date_trunc('month', a.data_atendimento);

-- Histórico do cliente (RF03/RF13): procedimentos realizados, datas e profissionais
create view vw_historico_cliente with (security_invoker = true) as
select c.id_cliente, c.nome as cliente, a.data_atendimento, a.horario_atendimento,
       pr.nome as procedimento, p.nome as profissional
  from atendimento a
  join cliente c       on c.id_cliente = a.id_cliente
  join procedimento pr on pr.id_procedimento = a.id_procedimento
  join profissional p  on p.id_profissional = a.id_profissional;

-- RF15: comissão por profissional e mês (percentual da categoria sobre o valor pago)
create view vw_comissao_profissional with (security_invoker = true) as
select p.id_profissional, p.nome as profissional, c.nome as categoria,
       date_trunc('month', a.data_atendimento)::date as mes,
       sum(pg.valor) as valor_cobrado,
       c.percentual_comissao,
       round(sum(pg.valor) * c.percentual_comissao / 100, 2) as comissao
  from atendimento a
  join profissional p        on p.id_profissional = a.id_profissional
  left join categoria_profissional c on c.id_categoria = p.id_categoria
  join pagamento pg          on pg.id_agendamento = a.id_agendamento
 group by p.id_profissional, p.nome, c.nome, c.percentual_comissao,
          date_trunc('month', a.data_atendimento);


